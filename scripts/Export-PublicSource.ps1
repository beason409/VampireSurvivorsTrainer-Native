#requires -Version 7.4
[CmdletBinding()]
param(
    [string]$SourceDirectory = (Split-Path $PSScriptRoot -Parent),
    [string[]]$ForbiddenText = @()
)
$ErrorActionPreference = 'Stop'
$sourceRoot = [IO.Path]::TrimEndingDirectorySeparator([IO.Path]::GetFullPath($SourceDirectory))
if (!(Test-Path -LiteralPath $sourceRoot -PathType Container)) { throw 'Source directory does not exist.' }
$exportBase = Join-Path $sourceRoot 'artifacts/public'
$exportId = [DateTime]::UtcNow.ToString('yyyyMMdd-HHmmss-fff') + '-' + [Guid]::NewGuid().ToString('N').Substring(0,6)
$exportDirectory = Join-Path $exportBase $exportId
$manifestPath = Join-Path $exportBase ($exportId + '.manifest.json')
$plan = [Collections.Generic.List[object]]::new()
$names = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$utf8 = [Text.UTF8Encoding]::new($false, $true)

function Assert-NoLinks([string]$Path) {
    $current = [IO.Path]::GetFullPath($Path)
    if ($current -ne $sourceRoot -and !$current.StartsWith($sourceRoot + [IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase)) {
        throw 'Export path is outside the source directory.'
    }
    while ($current.Length -ge $sourceRoot.Length) {
        if (Test-Path -LiteralPath $current) {
            if (((Get-Item -LiteralPath $current -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                throw 'Public export refuses linked source or destination paths.'
            }
        }
        if ($current -eq $sourceRoot) { break }
        $current = [IO.Path]::GetDirectoryName($current)
    }
}
Assert-NoLinks $sourceRoot
Assert-NoLinks $exportBase

# Do not bake a developer's profile path, account ID or workspace into the
# public script itself. Extra private identifiers are supplied at invocation.
$markers = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
$automatic = @($sourceRoot, [Environment]::GetFolderPath([Environment+SpecialFolder]::UserProfile))
$sourceParent = [IO.Path]::GetDirectoryName($sourceRoot)
if ($sourceParent -and $sourceParent -ne [IO.Path]::GetPathRoot($sourceParent)) { $automatic += $sourceParent }
foreach ($marker in @($automatic) + @($ForbiddenText)) {
    if ([string]::IsNullOrWhiteSpace($marker) -or $marker.Length -lt 3) { continue }
    foreach ($variant in @($marker, $marker.Replace('\','/'), $marker.Replace('\','\\'))) { [void]$markers.Add($variant) }
}
function Assert-PublicText([string]$RelativePath, [string]$Text) {
    foreach ($marker in $markers) {
        if ($RelativePath.Contains($marker,[StringComparison]::OrdinalIgnoreCase) -or $Text.Contains($marker,[StringComparison]::OrdinalIgnoreCase)) {
            throw ('Private identifier or absolute workspace/profile path found in export candidate: ' + $RelativePath)
        }
    }
    if ($Text -match '(?i)(?:steam[\\/]+userdata|userdata)[\\/]+[0-9]{5,12}(?:[\\/]|$)') {
        throw ('A concrete Steam userdata account path was found in export candidate: ' + $RelativePath)
    }
    if ($Text -match '(?i)\bgh[pousr]_[A-Za-z0-9]{30,}\b|\bgithub_pat_[A-Za-z0-9_]{30,}\b|-----BEGIN (?:RSA |EC |OPENSSH |ENCRYPTED )?PRIVATE KEY-----') {
        throw ('A credential marker was found in export candidate: ' + $RelativePath)
    }
}
function Add-File([string]$SourceRelative, [string]$TargetRelative = $SourceRelative, [switch]$OriginalIcon, [switch]$PreviewPng) {
    $source = [IO.Path]::GetFullPath((Join-Path $sourceRoot $SourceRelative))
    if (!(Test-Path -LiteralPath $source -PathType Leaf)) { throw ('Required public source file is missing: ' + $SourceRelative) }
    Assert-NoLinks $source
    $target = $TargetRelative.Replace('\','/')
    if ($target.StartsWith('/') -or $target.Contains(':') -or @($target.Split('/') | Where-Object { $_ -in @('','.','..') }).Count -gt 0 -or !$names.Add($target)) {
        throw ('Duplicate or invalid public destination path: ' + $target)
    }
    $bytes = [IO.File]::ReadAllBytes($source)
    if ($OriginalIcon) {
        # This exact asset is original artwork generated by the adjacent public
        # generator. No general game-art or binary-directory copying is allowed.
        if ($SourceRelative.Replace('\','/') -cne 'src/Trainer.Desktop/Assets/App.ico' -or $target -cne 'src/Trainer.Desktop/Assets/App.ico') { throw 'Only the original application icon is allowed as a binary source asset.' }
        if ($bytes.Length -lt 22 -or [BitConverter]::ToUInt16($bytes,0) -ne 0 -or [BitConverter]::ToUInt16($bytes,2) -ne 1) { throw 'The original application icon has an invalid ICO header.' }
        $imageCount = [BitConverter]::ToUInt16($bytes,4)
        $tableEnd = 6 + 16 * $imageCount
        if ($imageCount -eq 0 -or $imageCount -gt 256 -or $tableEnd -gt $bytes.Length) { throw 'The original application icon has an invalid image table.' }
        for ($index=0; $index -lt $imageCount; $index++) {
            $imageLength = [BitConverter]::ToUInt32($bytes,6 + 16*$index + 8)
            $imageOffset = [BitConverter]::ToUInt32($bytes,6 + 16*$index + 12)
            if ($imageLength -eq 0 -or $imageOffset -lt $tableEnd -or [long]$imageOffset + $imageLength -gt $bytes.Length) { throw 'The original application icon has an invalid image range.' }
        }
        Assert-PublicText $target ([Text.Encoding]::Latin1.GetString($bytes))
        Assert-PublicText $target ([Text.Encoding]::Unicode.GetString($bytes))
        $plan.Add([pscustomobject]@{ path=$target; source=$SourceRelative.Replace('\','/'); bytes=$bytes; normalizedDocumentation=$false; binaryAsset='original-application-icon' })
        return
    }
    if ($PreviewPng) {
        if ($SourceRelative.Replace('\','/') -cnotin @('docs/public/images/features.png','docs/images/features.png') -or $target -cne 'docs/images/features.png') { throw 'Only the reviewed interface preview is allowed as a PNG source asset.' }
        $signature = [byte[]](137,80,78,71,13,10,26,10)
        if ($bytes.Length -lt 33) { throw 'The reviewed preview is not a complete PNG.' }
        for ($index=0; $index -lt 8; $index++) {
            if ($bytes[$index] -ne $signature[$index]) { throw 'The reviewed preview has an invalid PNG signature.' }
        }
        if ([Convert]::ToHexString($bytes[8..15]) -ne '0000000D49484452') { throw 'The reviewed preview has an invalid PNG image header.' }
        Assert-PublicText $target ([Text.Encoding]::Latin1.GetString($bytes))
        Assert-PublicText $target ([Text.Encoding]::Unicode.GetString($bytes))
        $plan.Add([pscustomobject]@{ path=$target; source=$SourceRelative.Replace('\','/'); bytes=$bytes; normalizedDocumentation=$false; binaryAsset='reviewed-interface-preview' })
        return
    }
    try { $text = $utf8.GetString($bytes) }
    catch { throw ('A whitelisted source file is not UTF-8 text: ' + $SourceRelative) }
    if ($text.Contains([char]0)) { throw ('A binary file is not allowed by the source allowlist: ' + $SourceRelative) }
    $normalized = $false
    # Documentation examples become clone-relative. Source and license bytes
    # are otherwise preserved, rather than silently rewriting implementation.
    if ([IO.Path]::GetExtension($source).Equals('.md',[StringComparison]::OrdinalIgnoreCase)) {
        $portable = $text.Replace($sourceRoot,'.',[StringComparison]::OrdinalIgnoreCase)
        $portable = $portable.Replace($sourceRoot.Replace('\','/'),'.',[StringComparison]::OrdinalIgnoreCase)
        if ($portable -cne $text) { $text=$portable; $bytes=$utf8.GetBytes($text); $normalized=$true }
    }
    Assert-PublicText $target $text
    if ($target -ceq 'src/Trainer.Desktop/Assets/App.svg') {
        # The editable icon is artwork, not an export of an editor session.
        # Reject scripts, linked images, fonts and editor metadata before a
        # public snapshot can include the asset.
        $settings = [Xml.XmlReaderSettings]::new()
        $settings.DtdProcessing = [Xml.DtdProcessing]::Prohibit
        $settings.XmlResolver = $null
        $svgTextReader = [IO.StringReader]::new($text)
        $reader = [Xml.XmlReader]::Create($svgTextReader,$settings)
        try {
            $document = [Xml.XmlDocument]::new()
            $document.XmlResolver = $null
            $document.Load($reader)
            foreach ($element in $document.SelectNodes('//*')) {
                if ($element.LocalName -notin @('svg','g','path','rect','circle','ellipse','polygon','polyline','line','title','desc','defs','linearGradient','radialGradient','stop','clipPath')) {
                    throw 'Public icon SVG must contain self-contained vector artwork only.'
                }
                foreach ($attribute in $element.Attributes) {
                    if ($attribute.LocalName -eq 'href' -or $attribute.LocalName -match '^on' -or $attribute.Value -match '(?i)url\((?!#)') {
                        throw 'Public icon SVG must not contain external references or executable content.'
                    }
                }
            }
        }
        finally { $reader.Dispose(); $svgTextReader.Dispose() }
    }
    if ($target -eq 'config/supported-game.json') {
        $supported = $text | ConvertFrom-Json
        if (![string]::IsNullOrEmpty([string]$supported.gameDirectory)) { throw 'Public supported-game.json must have an empty gameDirectory.' }
    }
    $plan.Add([pscustomobject]@{ path=$target; source=$SourceRelative.Replace('\','/'); bytes=$bytes; normalizedDocumentation=$normalized; binaryAsset=$null })
}
function Add-Tree([string]$Directory, [string[]]$Extensions, [string[]]$ExcludedSegments = @()) {
    $directoryPath = Join-Path $sourceRoot $Directory
    if (!(Test-Path -LiteralPath $directoryPath -PathType Container)) { throw ('Required public source directory is missing: ' + $Directory) }
    Assert-NoLinks $directoryPath
    $pending = [Collections.Generic.Stack[string]]::new()
    $pending.Push($directoryPath)
    while ($pending.Count -gt 0) {
        $current = $pending.Pop()
        foreach ($entry in Get-ChildItem -LiteralPath $current -Force) {
            if ($entry.PSIsContainer) {
                if ($entry.Name -in @('bin','obj','artifacts','.artifacts','results','.git') + $ExcludedSegments) { continue }
                Assert-NoLinks $entry.FullName
                $pending.Push($entry.FullName)
            }
            elseif ($entry.Extension -in $Extensions -or $entry.Name -in @('LICENSE','Dockerfile')) {
                Assert-NoLinks $entry.FullName
                Add-File ([IO.Path]::GetRelativePath($sourceRoot,$entry.FullName))
            }
        }
    }
}

