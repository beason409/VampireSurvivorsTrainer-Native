# Validate every in-memory snapshot before creating a destination. Failed
# privacy scans cannot leave a half-exported source directory for publication.
New-Item -ItemType Directory -Path $exportBase -Force | Out-Null
New-Item -ItemType Directory -Path $exportDirectory | Out-Null
$files = [Collections.Generic.List[object]]::new()
foreach ($entry in $plan | Sort-Object path) {
    $destination = Join-Path $exportDirectory $entry.path
    $parent = [IO.Path]::GetDirectoryName($destination)
    [IO.Directory]::CreateDirectory($parent) | Out-Null
    $stream = [IO.File]::Open($destination,[IO.FileMode]::CreateNew,[IO.FileAccess]::Write,[IO.FileShare]::None)
    try { $stream.Write($entry.bytes,0,$entry.bytes.Length) } finally { $stream.Dispose() }
    $savedBytes = [IO.File]::ReadAllBytes($destination)
    if ($entry.binaryAsset) {
        Assert-PublicText $entry.path ([Text.Encoding]::Latin1.GetString($savedBytes))
        Assert-PublicText $entry.path ([Text.Encoding]::Unicode.GetString($savedBytes))
    }
    else { Assert-PublicText $entry.path ($utf8.GetString($savedBytes)) }
    $files.Add([pscustomobject]@{ path=$entry.path; source=$entry.source; length=$entry.bytes.Length; sha256=(Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash; normalizedDocumentation=$entry.normalizedDocumentation; binaryAsset=$entry.binaryAsset })
}
